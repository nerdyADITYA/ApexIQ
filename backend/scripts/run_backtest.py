"""Usage: python scripts/run_backtest.py 2024  -> writes docs/evaluation-report.md"""
import sys
import warnings
from pathlib import Path

sys.path.insert(0, ".")
warnings.filterwarnings("ignore")

from app.core.database import SessionLocal  # noqa: E402
from app.ml import evaluation as ev  # noqa: E402
from app.services.frames import season_results_frame  # noqa: E402


def md(df, fmt=".3f"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f"{v:{fmt}}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


if __name__ == "__main__":
    year = int(sys.argv[1])
    with SessionLocal() as db:
        res = season_results_frame(db, year)
    total_rounds = int(res["round"].max())
    totals = (res["race_points"] + res["sprint_points"]).groupby(res["driver"]).sum()
    champion = totals.idxmax()

    pred = ev.backtest_races(res)
    nested, chosen = ev.backtest_sharpened(res)
    pred = __import__("pandas").concat([pred, nested], ignore_index=True)
    summary = ev.summarise(pred)
    champ = {d: ev.backtest_championship(res, champion, total_rounds, decay=d) for d in (1.0, 0.8)}
    best = ev.NESTED
    cal = {t: ev.calibration_table(g["y"], g["p"]) for t, g in pred[pred["model"] == best].groupby("target")}

    out = [f"# Evaluation report: {year}", "",
           "Generated by `backend/scripts/run_backtest.py`. Every prediction for round *r* uses only rounds < *r*.", "",
           f"- Season: {year}, {total_rounds} rounds, first {4} used as warm-up only; predicted rounds 5 to {total_rounds}.",
           f"- Race-level sample: {pred[pred.model == best].groupby('target').size().iloc[0]} driver-race pairs per model/target.",
           "- Pre-qualifying forecast: grid positions are NOT used (they would not be known).", "",
           "## Race outcome probabilities (lower is better)", "",
           "`gain_vs_uniform` = mean per-race log-loss improvement over the uniform baseline, with a 95% bootstrap "
           "interval over races. An interval that includes 0 means the gain is not distinguishable from noise.", "",
           md(summary), ""]
    for t, tab in cal.items():
        out += [f"### Calibration: {best}, {t}", "", md(tab), ""]
    out += ["## Sharpening exponent chosen per round (expanding window, earlier rounds only)", "", md(chosen, ".2f"), ""]
    out += ["## Championship forecast vs actual champion", "",
            f"Actual champion: **{champion}**. Probability the model assigned to them after each round. "
            "This is a single outcome, so it illustrates behaviour but is not statistical evidence of quality.", ""]
    for d, tab in champ.items():
        out += [f"### decay {d}", "", md(tab), ""]
    out += ["## Limitations", "",
            "- One season only; no cross-era or cross-regulation evaluation yet.",
            "- Win probabilities rest on ~19 positive events per model, so their intervals are wide.",
            "- DNF probability is a fixed 5% for every driver; sprint races remaining are ignored in the championship simulation.",
            "- Strengths use race points only; no qualifying pace, car-specific or circuit features yet."]
    path = Path("..") / "docs" / "evaluation-report.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(summary.to_string(index=False))
    print(chosen.T.to_string(header=False))
    print("written", path.resolve())
